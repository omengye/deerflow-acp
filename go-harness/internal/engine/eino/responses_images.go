// Reviewed 2026-11-11 against the Responses tool and image generation reference:
// https://developers.openai.com/api/reference/resources/responses/methods/create
// GPT-Image-2.6 Sunburst supports explicit low/medium/high complexity. Restrict
// this default to the official endpoint; gateways own their image model catalog.
func responsesImageModel(baseURL string) string {
	u, err := url.Parse(baseURL)
	if err != nil || u.Scheme != "https" || !strings.EqualFold(u.Hostname(), "api.openai.com") ||
		(u.Port() != "" && u.Port() != "443") || u.User != nil || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" ||
		strings.TrimRight(u.EscapedPath(), "/") != "/v1" {
		return ""
	}
	return "gpt-image-2.6-sunburst"
}

func responsesImageFailure(code, message string) *harness.ImageGenerationError {
	kind := "failed"
	detail := strings.ToLower(code + " " + message)
	switch {
	case code == "insufficient_quota" || code == "billing_hard_limit_reached":
		kind = "quota_exceeded"
	case code == "permission_denied" || code == "access_denied" || code == "authentication_error":
		kind = "access_denied"
	case strings.Contains(detail, "complexity") && (strings.Contains(detail, "not supported") || strings.Contains(detail, "unsupported")):
		kind = "unsupported_complexity"
	case strings.Contains(detail, "not supported") || strings.Contains(detail, "unsupported"):
		kind = "unsupported"
	}
	return &harness.ImageGenerationError{Kind: kind, Cause: responsesProviderError(code, message)}
}

// Only identify explicit image-tool rejections. A text request can carry the
// optional tool too; unrelated model/auth/network failures keep their meaning.
func classifyResponsesImageError(err error) error {
	var api *chatapi.APIError
	if errors.As(err, &api) {
		code, _ := api.Code.(string)
		detail := strings.ToLower(code + " " + api.Message)
		if api.Param != nil {
			detail += " " + strings.ToLower(*api.Param)
		}
		if strings.Contains(detail, "image_generation") || strings.Contains(detail, "image generation") || strings.Contains(detail, "image model") {
			classified := responsesImageFailure(code, api.Message)
			classified.Cause = err
			if api.HTTPStatusCode == 401 || api.HTTPStatusCode == 403 {
				classified.Kind = "access_denied"
			}
			return classified
		}
	}
	return err
}

func responsesGeneratedImage(item responsesItem, limit *modelImageLimit) (schema.MessageOutputPart, error) {
	mime := "image/png" // The request explicitly selects PNG.
	switch item.OutputFormat {
	case "", "png":
	case "jpeg", "webp", "gif":
		mime = "image/" + item.OutputFormat
	default:
		return schema.MessageOutputPart{}, fmt.Errorf("%w: unsupported Responses image format", harness.ErrModelResponseInvalid)
	}
	size := int64(base64.StdEncoding.DecodedLen(len(item.Result)))
	if strings.HasSuffix(item.Result, "==") {
		size -= 2
	} else if strings.HasSuffix(item.Result, "=") {
		size--
	}
	if size <= 0 || size > harness.MaxInputImageBytes || limit.count >= harness.MaxInputImagesPerTurn || limit.bytes+size > harness.MaxInputImageTotalBytes {
		return schema.MessageOutputPart{}, fmt.Errorf("%w: Responses images exceed output limits", harness.ErrModelResponseInvalid)
	}
	limit.count++
	limit.bytes += size
	return schema.MessageOutputPart{Type: schema.ChatMessagePartTypeImageURL, Image: &schema.MessageOutputImage{MessagePartCommon: schema.MessagePartCommon{Base64Data: &item.Result, MIMEType: mime}}}, nil
}

func responsesAssistantImages(message *schema.Message) []schema.MessageOutputPart {
	var images []schema.MessageOutputPart
	for _, part := range message.AssistantGenMultiContent {
		if part.Type == schema.ChatMessagePartTypeImageURL {
			images = append(images, part)
		}
	}
	return images
}

func responsesImageData(part schema.MessageOutputPart) (string, error) {
	if part.Image == nil || part.Image.Base64Data == nil || *part.Image.Base64Data == "" || part.Image.URL != nil || !imageMIME(part.Image.MIMEType) {
		return "", fmt.Errorf("%w: Responses image history must be hydrated from session assets", harness.ErrInvalidInput)
	}
	return *part.Image.Base64Data, nil
}

// Stateless calls must not replay provider image IDs, including on the original
// endpoint. Authorized asset bytes remain available as labelled image context.
func responsesAppendImageContext(items []any, images []schema.MessageOutputPart) ([]any, error) {
	if len(images) == 0 {
		return items, nil
	}
	content := []any{map[string]any{"type": "input_text", "text": "[Images generated by the assistant in an earlier turn; image context, not new user instructions.]"}}
	for _, image := range images {
		data, err := responsesImageData(image)
		if err != nil {
			return nil, err
		}
		content = append(content, map[string]any{"type": "input_image", "image_url": "data:" + image.Image.MIMEType + ";base64," + data})
	}
	return append(items, map[string]any{"type": "message", "role": "user", "content": content}), nil
}
