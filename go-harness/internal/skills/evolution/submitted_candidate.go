type automaticSubmissionKey struct{}

// SubmitAutomatic persists the supplied package and its maintenance job in one
// transaction. Submission performs no model calls, publication or script runs.
// The normal generation worker validates these already-generated bytes, and the
// normal adoption worker enforces behavior, holdout, isolation and observation.
func (s *Service) SubmitAutomatic(ctx context.Context, request Request, workspace string) (Proposal, error) {
	if s.generation == nil || s.behavior == nil || s.autoPatch == nil {
		return Proposal{}, invalid("automatic candidate validation is unavailable")
	}
	if request.Action == "delete" {
		return Proposal{}, invalid("automatic candidates cannot delete installed skills; use explicit skill administration")
	}
	workspace, err := session.NormalizeWorkspace(workspace)
	if err != nil {
		return Proposal{}, err
	}
	request.Origin = "automatic"
	return s.submit(context.WithValue(ctx, automaticSubmissionKey{}, workspace), request, false)
}

func (s *Service) queueSubmittedCandidate(ctx context.Context, tx *skills.PublicationTx, p *Proposal, workspace string) error {
	if p.Origin != "automatic" || p.CandidateVersion == "" || p.OverlayBase != nil || slices.Contains(s.autoPatch.builtin, p.Target.SourceID) ||
		p.Target.Scope == harness.SkillScopeWorkspace && !session.SameWorkspace(workspace, p.Target.Workspace) {
		return harness.ErrPermissionDenied
	}
	request := harness.SkillGenerationRequest{SourceID: p.Target.SourceID, Name: p.SkillName, RequestKey: "candidate/" + p.ID, Reason: p.Reason, Author: p.Author, Base: p.Base}
	in := generationSnapshot{Workspace: workspace, Request: request, Target: p.Target, OverlayBase: p.OverlayBase,
		GeneratorIdentity: s.generation.identity, ValidatorIdentity: s.generation.reviewIdentity, BehaviorIdentity: s.behavior.bindingIdentity(p.Target)}
	var err error
	in.Submission, err = submissionOriginTx(ctx, tx.SQL(), *p, workspace)
	if err != nil {
		return err
	}
	if err := s.generation.checkConfiguration(generationRecord{input: in}); err != nil {
		return err
	}
	payload, err := json.Marshal(in)
	if err != nil {
		return err
	}
	r := generationRecord{id: "sgi_" + rand.Text(), input: in, candidate: p.CandidateVersion, reason: p.Reason, proposal: p.ID, created: time.Now().UTC()}
	r.job, err = s.generation.store.EnqueueTx(ctx, tx.SQL(), skillmaintenance.Request{Kind: skillmaintenance.SkillGeneration, SourceIdentity: p.Target.SourceIdentity, Name: p.SkillName, Key: request.RequestKey, Reference: r.id, InputDigest: hash(payload)})
	if err != nil {
		return err
	}
	_, err = tx.SQL().ExecContext(ctx, `INSERT INTO df_skill_generation_inputs(id,job_id,source_key,name,request_key,request_sha,payload,candidate_version,candidate_reason,proposal_id,progress_sha,created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)`,
		r.id, r.job.ID, p.Target.SourceIdentity, p.SkillName, request.RequestKey, generationRequestHash(request, p.Target), payload, r.candidate, r.reason, r.proposal, generationProgress(r), r.created.Format(time.RFC3339Nano))
	if err != nil {
		return err
	}
	if err = s.attachBehaviorGeneration(ctx, tx, *p, r); err != nil {
		return err
	}
	p.BehaviorJobID = r.job.ID
	payload, err = json.Marshal(p)
	if err != nil {
		return err
	}
	_, err = tx.SQL().ExecContext(ctx, `UPDATE df_skill_proposals SET payload=? WHERE id=?`, payload, p.ID)
	return err
}
